"""`detect` tests, including the P1-1 gate.

Review #2 named the gate: *"the determinism CI currently proves that sorting
strings is deterministic, not that building a lockfile from a filesystem is."*
So these tests build from a real fixture tree on disk, where dirent ordering,
NFD paths, symlinks, and size caps actually enter.
"""

from __future__ import annotations

import os
import unicodedata
from pathlib import Path

import pytest

from svarupa.detect import FileRole, ScanLimits, detect


def write(root: Path, rel: str, text: str = "x = 1\n") -> Path:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf8")
    return p


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    """A tree that exercises every classification branch."""
    r = tmp_path / "repo"
    r.mkdir()
    write(r, "src/api/main.py")
    write(r, "src/api/routes.py")
    write(r, "src/auth/jwt.py")
    write(r, "web/app.ts")
    write(r, "web/util.tsx")
    write(r, "schema/init.sql", "CREATE TABLE t (id int);\n")
    write(r, "docker-compose.yml", "services:\n  api:\n    image: x\n")
    write(r, "pyproject.toml", "[project]\nname='x'\n")
    # excluded roles
    write(r, "tests/test_api.py")
    write(r, "src/api/routes_test.py")
    write(r, "web/app.spec.ts")
    write(r, "src/pb/thing_pb2.py")
    write(r, "vendor/lib/dep.py")
    write(r, "src/generated/client.py")
    write(r, "src/banner.py", "# Code generated by protoc. DO NOT EDIT.\nx = 1\n")
    # never walked
    write(r, "node_modules/pkg/index.js")
    write(r, ".venv/lib/thing.py")
    write(r, "dist/bundle.js")
    return r


