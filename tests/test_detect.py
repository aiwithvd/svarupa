def roles(repo: Path) -> dict[str, FileRole]:
    return {f.path: f.role for f in detect(repo).files}


def test_source_files_are_source(repo: Path) -> None:
    r = roles(repo)
    for p in ("src/api/main.py", "src/auth/jwt.py", "web/app.ts", "web/util.tsx"):
        assert r[p] is FileRole.SOURCE, p


@pytest.mark.parametrize(
    ("path", "role"),
    [
        ("tests/test_api.py", FileRole.TEST),
        ("src/api/routes_test.py", FileRole.TEST),
        ("web/app.spec.ts", FileRole.TEST),
        ("src/pb/thing_pb2.py", FileRole.GENERATED),
        ("src/generated/client.py", FileRole.GENERATED),
        ("src/banner.py", FileRole.GENERATED),
        ("vendor/lib/dep.py", FileRole.VENDORED),
        ("docker-compose.yml", FileRole.CONFIG),
        ("pyproject.toml", FileRole.CONFIG),
    ],
)
def test_role_classification(repo: Path, path: str, role: FileRole) -> None:
    assert roles(repo)[path] is role


def test_generated_banner_is_detected_by_content(repo: Path) -> None:
    """`src/banner.py` has an innocent name; only the banner gives it away."""
    assert roles(repo)["src/banner.py"] is FileRole.GENERATED


def test_excluded_directories_are_never_walked(repo: Path) -> None:
    paths = {f.path for f in detect(repo).files}
    assert not any(p.startswith(("node_modules/", ".venv/", "dist/")) for p in paths)


def test_only_source_and_config_reach_architecture(repo: Path) -> None:
    """S5: test, generated and vendored code is 30-50% of files and imports
    everything. It stays in the graph but must not shape architecture."""
    arch = {f.path for f in detect(repo).architecture_files}
    assert "src/api/main.py" in arch
    assert "docker-compose.yml" in arch
    for excluded in (
        "tests/test_api.py",
        "src/pb/thing_pb2.py",
        "vendor/lib/dep.py",
        "src/generated/client.py",
    ):
        assert excluded not in arch, excluded


def test_language_detection(repo: Path) -> None:
    langs = dict(detect(repo).languages())
    assert langs["python"] >= 4
    assert langs["typescript"] >= 2
    assert langs["sql"] == 1


