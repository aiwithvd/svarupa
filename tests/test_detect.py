@pytest.mark.determinism
def test_scan_is_byte_stable_across_repeated_runs(repo: Path) -> None:
    runs = [tuple(detect(repo).files) for _ in range(10)]
    assert len(set(runs)) == 1


@pytest.mark.determinism
def test_scan_order_is_independent_of_creation_order(tmp_path: Path) -> None:
    """Dirent order is filesystem-dependent and must never leak.

    Two trees with identical contents created in opposite orders must scan
    identically. On many filesystems creation order *is* dirent order, so this
    would fail against an unsorted `os.scandir`.
    """
    names = ["zeta.py", "alpha.py", "mid.py", "Beta.py", "_under.py"]
    a, b = tmp_path / "a", tmp_path / "b"
    for root, order in ((a, names), (b, list(reversed(names)))):
        root.mkdir()
        for n in order:
            write(root, f"src/{n}")

    fa = [f.path for f in detect(a).files]
    fb = [f.path for f in detect(b).files]
    assert fa == fb == sorted(fa)


@pytest.mark.determinism
def test_nfd_paths_on_disk_are_normalized(tmp_path: Path) -> None:
    """The real filesystem leg of the NFC guard.

    A directory created with explicit NFD bytes must scan as NFC, or two
    machines produce two different lockfiles for the same tree.
    """
    r = tmp_path / "repo"
    r.mkdir()
    nfd = unicodedata.normalize("NFD", "café")
    write(r, f"src/{nfd}/mod.py")
    write(r, "src/plain/mod.py")

    scan = detect(r)
    assert len(scan.files) == 2
    for f in scan.files:
        assert unicodedata.is_normalized("NFC", f.path), f"{f.path!r} is not NFC"


@pytest.mark.determinism
def test_content_hash_tracks_content_not_metadata(repo: Path) -> None:
    before = {f.path: f.content_hash for f in detect(repo).files}
    os.utime(repo / "src/api/main.py", (0, 0))  # touch mtime only
    after = {f.path: f.content_hash for f in detect(repo).files}
    assert before == after, "mtime must not affect the hash"

    write(repo, "src/api/main.py", "x = 2\n")
    changed = {f.path: f.content_hash for f in detect(repo).files}
    assert changed["src/api/main.py"] != before["src/api/main.py"]
    assert changed["src/auth/jwt.py"] == before["src/auth/jwt.py"], "locality"


@pytest.mark.determinism
def test_absolute_path_of_the_repo_never_leaks(tmp_path: Path) -> None:
    """The same tree at two locations must scan identically.

    An absolute path leaking into a record would make the lockfile depend on
    where the repo happens to be checked out.
    """
    for name in ("here", "somewhere/else/deeper"):
        d = tmp_path / name
        d.mkdir(parents=True)
        write(d, "src/a.py")
        write(d, "src/b.py")

    one = tuple(detect(tmp_path / "here").files)
    two = tuple(detect(tmp_path / "somewhere/else/deeper").files)
    assert one == two
