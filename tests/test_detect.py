def test_symlink_outside_root_is_diagnosed_and_not_followed(repo: Path, tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "secret.py").write_text("SECRET = 1\n")
    try:
        (repo / "link").symlink_to(outside, target_is_directory=True)
    except (OSError, NotImplementedError):
        pytest.skip("symlinks unavailable")

    scan = detect(repo)
    assert not any(f.path.startswith("link/") for f in scan.files)
    codes = {d.code for d in scan.diagnostics}
    assert "SVA-D-001" in codes, "escaping symlink must be diagnosed, not silently skipped"


def test_symlink_loop_does_not_hang(repo: Path) -> None:
    try:
        (repo / "src" / "loop").symlink_to(repo / "src", target_is_directory=True)
    except (OSError, NotImplementedError):
        pytest.skip("symlinks unavailable")
    scan = detect(repo)  # must terminate
    assert not any("/loop/" in f.path for f in scan.files)


def test_oversized_files_are_skipped_with_a_diagnostic(repo: Path) -> None:
    write(repo, "src/huge.py", "# pad\n" * 5000)
    scan = detect(repo, ScanLimits(max_file_bytes=1000))
    assert "src/huge.py" not in {f.path for f in scan.files}
    assert "SVA-D-002" in {d.code for d in scan.diagnostics}


def test_file_cap_reports_an_incomplete_scan(repo: Path) -> None:
    scan = detect(repo, ScanLimits(max_files=3))
    assert len(scan.files) == 3
    assert "SVA-D-003" in {d.code for d in scan.diagnostics}, (
        "a truncated scan must say so; silently partial results are worse than failing"
    )


def test_unreadable_directory_is_reported_not_fatal(repo: Path) -> None:
    if os.name != "posix" or os.geteuid() == 0:
        pytest.skip("needs posix and a non-root user")
    locked = repo / "src" / "locked"
    locked.mkdir()
    (locked / "a.py").write_text("x = 1\n")
    locked.chmod(0o000)
    try:
        scan = detect(repo)
        assert "SVA-D-005" in {d.code for d in scan.diagnostics}
        assert any(f.path == "src/api/main.py" for f in scan.files), "scan must continue"
    finally:
        locked.chmod(0o755)


