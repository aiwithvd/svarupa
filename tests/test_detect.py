def test_pnpm_workspace_detected(repo: Path) -> None:
    (repo / "pnpm-workspace.yaml").write_text("packages:\n  - 'packages/*'\n")
    kinds = {w.kind for w in detect(repo).workspaces}
    assert "pnpm" in kinds


def test_npm_workspace_detected_only_when_declared(repo: Path) -> None:
    write(repo, "package.json", '{"name":"x"}')
    assert "npm" not in {w.kind for w in detect(repo).workspaces}
    write(repo, "package.json", '{"name":"x","workspaces":["packages/*"]}')
    assert "npm" in {w.kind for w in detect(repo).workspaces}


def test_cargo_and_go_workspaces_detected(repo: Path) -> None:
    write(repo, "Cargo.toml", "[workspace]\nmembers = ['a']\n")
    write(repo, "go.work", "go 1.22\nuse ./a\n")
    kinds = {w.kind for w in detect(repo).workspaces}
    assert {"cargo", "go"} <= kinds


